"""
Scarlet Roasters · the operations database as Django models — a map of the tables you built.

The database came first. Weeks 1–4 designed it (ER model → relational schema → schema_v1.sql)
and built it on Neon by hand, in SQL. These classes do not create those tables; they DESCRIBE
them to Django, one class per table, so that Python code can ask the database questions
without writing the SQL by hand — and so that the admin can give the company a back office.

    class Meta:
        db_table = "coffees"     # which table this class stands for
        managed = False          # the table exists; Django never creates, alters or drops it

The rule for every line: the model must agree with the table that exists. Check it with

    python manage.py checkmodels      # reads the live database and compares, column by column
    python manage.py counts           # the eleven row counts, through the models

Conventions:
  * Field names are the column names. A ForeignKey named `customer` becomes the column
    customer_id — exactly what the schema has. Where the schema's foreign-key column does
    not end in _id (products.coffee, order_lines.sku, inventory.sku, order_no), db_column= says so.
  * on_delete=PROTECT: the schema's REFERENCES has no ON DELETE clause, so PostgreSQL refuses
    to delete a parent that still has children. PROTECT makes Django refuse first, with a
    readable error, instead of letting the database raise one.
  * The CHECK and UNIQUE constraints are IN THE DATABASE already (schema_v1.sql). Repeating
    them in Meta.constraints lets Django check them in a form before the database has to —
    the admin shows "Constraint … is violated" instead of a 500. `choices` is for the dropdown.
  * One table changed for the application: order_lines (schema v1.1, v1_1_order_lines.sql) —
    a generated surrogate key line_id, with the business key (order_no, line_no) kept UNIQUE,
    because Django's admin and forms need a single-column primary key.
"""

from django.db import models
from django.db.models import Q


# ---------------------------------------------------------------- master data

class Customer(models.Model):
    WHOLESALE, RETAIL = "Wholesale", "Retail"
    TYPES = [(WHOLESALE, "Wholesale"), (RETAIL, "Retail")]

    customer_id = models.IntegerField(primary_key=True)          # INTEGER PRIMARY KEY (the spreadsheet's ids)
    customer_name = models.CharField(max_length=80)
    customer_type = models.CharField(max_length=10, choices=TYPES)
    contact_name = models.CharField(max_length=80, null=True, blank=True)
    email = models.CharField(max_length=120, null=True, blank=True)   # rule 10 says unique; the two Daily Grinds say not yet
    phone = models.CharField(max_length=20, null=True, blank=True)
    credit_limit = models.DecimalField(max_digits=10, decimal_places=2, null=True, blank=True)
    payment_terms = models.CharField(max_length=10, null=True, blank=True)
    resale_cert = models.CharField(max_length=20, null=True, blank=True)
    customer_since = models.DateField(null=True, blank=True)

    class Meta:
        db_table = "customers"
        managed = False
        constraints = [
            models.CheckConstraint(condition=Q(customer_type__in=["Wholesale", "Retail"]), name="customers_customer_type_check"),
            models.CheckConstraint(condition=Q(credit_limit__gte=0) | Q(credit_limit__isnull=True), name="customers_credit_limit_check",
                                   violation_error_message="The credit limit cannot be negative."),
        ]

    def __str__(self):
        return self.customer_name


class Address(models.Model):
    address_id = models.AutoField(primary_key=True)              # GENERATED BY DEFAULT AS IDENTITY
    customer = models.ForeignKey(Customer, on_delete=models.PROTECT, related_name="addresses")  # column: customer_id
    street = models.CharField(max_length=80)
    city = models.CharField(max_length=40)
    state = models.CharField(max_length=2)                       # CHAR(2)
    zip = models.CharField(max_length=10)                        # zip -> city, state: kept on purpose (normalization exception)
    is_current = models.BooleanField(default=True)               # BOOLEAN NOT NULL DEFAULT TRUE

    class Meta:
        db_table = "addresses"
        managed = False
        verbose_name_plural = "addresses"
        constraints = [
            models.UniqueConstraint(fields=["customer", "street", "city", "state", "zip"], name="addresses_customer_id_street_city_state_zip_key"),
            # one current address per customer: the partial unique index addresses_one_current
            models.UniqueConstraint(fields=["customer"], condition=Q(is_current=True), name="addresses_one_current"),
        ]

    def __str__(self):
        return f"{self.street}, {self.city} {self.state} {self.zip}"


class Employee(models.Model):
    ROLES = [("Owner", "Owner"), ("Sales", "Sales"), ("Warehouse", "Warehouse"), ("Bookkeeping", "Bookkeeping")]

    employee_id = models.AutoField(primary_key=True)
    first_name = models.CharField(max_length=30)
    last_name = models.CharField(max_length=30)
    role = models.CharField(max_length=20, choices=ROLES)

    class Meta:
        db_table = "employees"
        managed = False
        constraints = [
            models.CheckConstraint(condition=Q(role__in=["Owner", "Sales", "Warehouse", "Bookkeeping"]), name="employees_role_check"),
        ]

    def __str__(self):
        return f"{self.first_name} {self.last_name}"


class Coffee(models.Model):
    coffee = models.CharField(max_length=40, primary_key=True)   # a natural key: the coffee's name
    origin = models.CharField(max_length=40)
    roast_level = models.CharField(max_length=20)
    supplier = models.CharField(max_length=40)
    green_lbs_on_hand = models.IntegerField()
    last_green_delivery = models.DateField(null=True, blank=True)

    class Meta:
        db_table = "coffees"
        managed = False
        constraints = [
            models.CheckConstraint(condition=Q(green_lbs_on_hand__gte=0), name="coffees_green_lbs_on_hand_check"),
        ]

    def __str__(self):
        return self.coffee


class Product(models.Model):
    sku = models.CharField(max_length=10, primary_key=True)      # a natural key: the SKU on the price list
    product_name = models.CharField(max_length=60)
    coffee = models.ForeignKey(Coffee, on_delete=models.PROTECT, null=True, blank=True,
                               db_column="coffee", related_name="products")   # NULL for the tote bag
    size = models.CharField(max_length=20, null=True, blank=True)
    retail_price = models.DecimalField(max_digits=8, decimal_places=2)       # today's list prices;
    wholesale_price = models.DecimalField(max_digits=8, decimal_places=2)    # the price charged is on order_lines
    active = models.BooleanField(default=True)

    class Meta:
        db_table = "products"
        managed = False
        constraints = [
            models.CheckConstraint(condition=Q(retail_price__gt=0), name="products_retail_price_check"),
            models.CheckConstraint(condition=Q(wholesale_price__gt=0), name="products_wholesale_price_check"),
        ]

    def __str__(self):
        return self.product_name


class Inventory(models.Model):
    # The primary key IS the foreign key: one inventory row per product, and only for products that exist.
    product = models.OneToOneField(Product, on_delete=models.PROTECT, primary_key=True,
                                   db_column="sku", related_name="inventory")
    on_hand_bags = models.IntegerField()                         # rule 1: never below zero (the CHECK)
    reorder_point = models.IntegerField()
    last_roast_date = models.DateField(null=True, blank=True)

    class Meta:
        db_table = "inventory"
        managed = False
        verbose_name_plural = "inventory"
        constraints = [
            models.CheckConstraint(condition=Q(on_hand_bags__gte=0), name="inventory_on_hand_bags_check"),
            models.CheckConstraint(condition=Q(reorder_point__gte=0), name="inventory_reorder_point_check"),
        ]

    def __str__(self):
        return f"{self.product_id}: {self.on_hand_bags} bags"


# ---------------------------------------------------------------- transaction data

class SalesOrder(models.Model):
    STATUSES = [(s, s) for s in ("Draft", "Confirmed", "Shipped", "Invoiced", "Paid", "Cancelled")]

    order_no = models.CharField(max_length=10, primary_key=True)
    customer = models.ForeignKey(Customer, on_delete=models.PROTECT, related_name="orders")        # customer_id
    order_date = models.DateField()
    status = models.CharField(max_length=10, choices=STATUSES)
    taken_by = models.ForeignKey(Employee, on_delete=models.PROTECT, null=True, blank=True,
                                 related_name="orders_taken")                                        # taken_by_id; NULL: a web order
    ship_to_address = models.ForeignKey(Address, on_delete=models.PROTECT, related_name="orders_shipped_here")  # ship_to_address_id

    class Meta:
        db_table = "sales_orders"
        managed = False
        constraints = [
            models.CheckConstraint(condition=Q(status__in=["Draft", "Confirmed", "Shipped", "Invoiced", "Paid", "Cancelled"]),
                                   name="sales_orders_status_check"),
        ]

    def __str__(self):
        return self.order_no


class OrderLine(models.Model):
    # The weak entity. schema v1.0 keyed it (order_no, line_no); Django's admin and forms need a
    # single-column primary key, so schema v1.1 (v1_1_order_lines.sql, run once in Neon) adds a
    # generated line_id and keeps (order_no, line_no) UNIQUE. Same rule, enforced by the database.
    line_id = models.AutoField(primary_key=True)
    order = models.ForeignKey(SalesOrder, on_delete=models.PROTECT, db_column="order_no", related_name="lines")
    line_no = models.IntegerField()
    product = models.ForeignKey(Product, on_delete=models.PROTECT, db_column="sku", related_name="order_lines")
    grind = models.CharField(max_length=15, null=True, blank=True)
    qty = models.IntegerField()
    unit_price = models.DecimalField(max_digits=8, decimal_places=2)   # the price on the order date (rule 8): a fact, not a copy

    class Meta:
        db_table = "order_lines"
        managed = False
        ordering = ["order", "line_no"]
        constraints = [
            models.UniqueConstraint(fields=["order", "line_no"], name="order_lines_order_no_line_no_key"),
            models.CheckConstraint(condition=Q(qty__gt=0), name="order_lines_qty_check"),
        ]

    def __str__(self):
        return f"{self.order_id} line {self.line_no}"

    @property
    def line_total(self):                  # what v_order_lines computes in SQL
        return self.qty * self.unit_price


class Shipment(models.Model):
    shipment_id = models.AutoField(primary_key=True)
    order = models.OneToOneField(SalesOrder, on_delete=models.PROTECT, db_column="order_no", related_name="shipment")  # one box per order
    ship_date = models.DateField()
    carrier = models.CharField(max_length=10, choices=[("Van", "Van"), ("UPS", "UPS")])
    tracking = models.CharField(max_length=30, null=True, blank=True)

    class Meta:
        db_table = "shipments"
        managed = False
        constraints = [
            models.CheckConstraint(condition=Q(carrier__in=["Van", "UPS"]), name="shipments_carrier_check"),
        ]

    def __str__(self):
        return f"{self.order_id} shipped {self.ship_date}"


class Invoice(models.Model):
    invoice_no = models.CharField(max_length=10, primary_key=True)
    order = models.OneToOneField(SalesOrder, on_delete=models.PROTECT, db_column="order_no", related_name="invoice")   # one invoice per order
    invoice_date = models.DateField()

    class Meta:
        db_table = "invoices"
        managed = False

    def __str__(self):
        return self.invoice_no


class Payment(models.Model):
    payment_id = models.AutoField(primary_key=True)
    order = models.ForeignKey(SalesOrder, on_delete=models.PROTECT, db_column="order_no", related_name="payments")   # retail orders have no invoice
    paid_date = models.DateField()

    class Meta:
        db_table = "payments"
        managed = False

    def __str__(self):
        return f"{self.order_id} paid {self.paid_date}"
